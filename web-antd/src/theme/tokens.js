/** 站点主题是否深色（服务端局部主题不改变全局 isDark） */
export function isDarkTheme(name) {
  const t = SITE_THEMES[name];
  return !!(t && t.isDark);
}

/** 把主题变量写到 <html>，供 Portal（body 内的 Modal/Drawer 等）统一使用 */
export function applyThemeVars(name) {
  if (typeof document === 'undefined') return;
  const root = document.documentElement;
  if (!root) return;
  const theme = SITE_THEMES[name] || SITE_THEMES[DEFAULT_THEME];
  Object.entries(theme.vars || {}).forEach(([k, v]) => {
    root.style.setProperty(`--pp-${k}`, v);
  });
  // 供 CSS 选择器/调试使用
  root.setAttribute('data-pp-theme', theme.name);
  if (theme.bodyBackground) root.style.setProperty('--pp-body-bg', theme.bodyBackground);
}

/** 服务器页局部主题变量（可直接展开到容器 style） */
export function getServersThemeVars(name) {
  return getThemeVars(name, 'servers');
}

