/* ---- 主题变量 → CSS 变量对象（--pp-*） ---- */
export function getThemeVars(name, scope = 'site') {
  const bag = scope === 'servers' ? SERVERS_THEMES : SITE_THEMES;
  const theme = bag[name] || bag[DEFAULT_THEME] || SITE_THEMES.light;
  const out = {};
  Object.entries(theme.vars || {}).forEach(([k, v]) => {
    out[`--pp-${k}`] = v;
  });
  return out;
}

