  // 生成Clash代理配置
  static generateClashProxy(meta, index) {
    switch (meta.protocol) {
      case 'vmess':
        return {
          name: `${meta.ps || 'VMess节点'} ${index}`,
          type: 'vmess',
          server: meta.add || '',
          port: meta.port || '',
          uuid: meta.id || '',
          alterId: meta.aid || '0',
          cipher: 'auto',
          tls: meta.tls === 'tls',
          skip_cert_verify: true,
          servername: meta.sni || '',
          network: meta.net || 'tcp',
          'ws-opts': {
            path: meta.path || '',
            headers: {
              Host: meta.host || ''
            }
          }
        };
        
      case 'vless':
        return {
          name: `${meta.ps || 'VLESS节点'} ${index}`,
          type: 'vless',
          server: meta.add || '',
          port: meta.port || '',
          uuid: meta.id || '',
          flow: meta.flow || '',
          tls: meta.tls === 'tls',
          servername: meta.sni || '',
          network: meta.net || 'tcp',
          'ws-opts': {
            path: meta.path || '',
            headers: {
              Host: meta.host || ''
            }
          }
        };
        
      case 'trojan':
        return {
          name: `${meta.remark || 'Trojan节点'} ${index}`,
          type: 'trojan',
          server: meta.address || '',
          port: meta.port || '',
          password: meta.password || '',
          sni: meta.sni || '',
          skip_cert_verify: true,
          udp: true
        };
        
      case 'ss':
        // 解析Shadowsocks
        try {
          const ssConfig = this.parseShadowsocks(meta.raw);
          return {
            name: `Shadowsocks节点 ${index}`,
            type: 'ss',
            server: ssConfig.server,
            port: ssConfig.port,
            cipher: ssConfig.method,
            password: ssConfig.password
          };
        } catch (error) {
          return null;
        }
        
      default:
        return null;
    }
  }

  // 解析Shadowsocks配置
  static parseShadowsocks(ssUrl) {
    // 移除ss://前缀
    const encoded = ssUrl.substring(5);
    
    // 处理可能的@符号格式
    if (encoded.includes('@')) {
      const match = encoded.match(/([^@]+)@([^#]+)#(.+)/);
      if (match) {
        const [, methodPassword, serverPort, remark] = match;
        const [server, port] = serverPort.split(':');
        
        // 解码method:password部分
        const decoded = Buffer.from(methodPassword, 'base64').toString();
        const [method, password] = decoded.split(':');
        
        return {
          method: method || 'aes-256-gcm',
          password: password || '',
          server: server || '',
          port: parseInt(port) || 443,
          remark: decodeURIComponent(remark || '')
        };
      }
    }
    
    // 完整base64编码格式
    const decoded = Buffer.from(encoded, 'base64').toString();
    const match = decoded.match(/([^:]+):([^@]+)@([^:]+):(\d+)/);
    
    if (match) {
      const [, method, password, server, port] = match;
      return {
        method,
        password,
        server,
        port: parseInt(port),
        remark: ''
      };
    }
    
    throw new Error('Invalid Shadowsocks configuration');
  }

  // 替换模板占位符
  static replaceTemplatePlaceholders(template, replacements) {
    let result = template;
    for (const [key, value] of Object.entries(replacements)) {
      result = result.replace(new RegExp(`{{${key}}}`, 'g'), value);
    }
    return result;
  }

