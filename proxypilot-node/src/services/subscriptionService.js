  // 批量生成配置
  static async batchGenerateConfigs(uuids, format = 'clash') {
    const results = [];
    
    for (const uuid of uuids) {
      try {
        let result;
        
        switch (format) {
          case 'clash':
            result = await this.generateClashConfig(uuid);
            break;
          case 'raw':
            result = await this.generateRawSubscription(uuid);
            break;
          default:
            result = {
              success: false,
              error: 'Unsupported format'
            };
        }
        
        results.push({
          uuid,
          ...result
        });
      } catch (error) {
        results.push({
          uuid,
          success: false,
          error: error.message
        });
      }
    }
    
    return results;
  }

  // 获取订阅统计信息
  static async getSubscriptionStats(uuid) {
    const configCount = await db('configs')
      .where({ uuid })
      .count('id as count')
      .first();
    
    const accessStats = await db('config_access_logs')
      .select(
        db.raw("query_type"),
        db.raw("COUNT(*) as count")
      )
      .where({ uuid })
      .groupBy('query_type');
    
    const lastAccess = await db('config_access_logs')
      .where({ uuid })
      .max('created_at as last_access')
      .first();
    
    const stats = {
      totalConfigs: parseInt(configCount.count),
      lastAccess: lastAccess.last_access,
      accessByType: {}
    };
    
    accessStats.forEach(stat => {
      stats.accessByType[stat.query_type] = parseInt(stat.count);
    });
    
    return {
      success: true,
      stats
    };
  }

  // 验证UUID是否存在
  static async validateUUID(uuid) {
    const exists = await db('configs')
      .where({ uuid })
      .first();
    
    return {
      exists: !!exists,
      configCount: exists ? await this.getConfigCount(uuid) : 0
    };
  }

  // 获取配置数量
  static async getConfigCount(uuid) {
    const result = await db('configs')
      .where({ uuid })
      .count('id as count')
      .first();
    
    return parseInt(result.count);
  }

  // 生成订阅链接
  static generateSubscriptionUrl(baseUrl, uuid, format = 'clash') {
    return `${baseUrl}/api/subscription/${uuid}/${format}`;
  }

  // 生成批量订阅链接
  static generateBatchSubscriptionUrl(baseUrl, uuids, format = 'clash') {
    const uuidString = uuids.join(',');
    return `${baseUrl}/api/subscription/batch/${uuidString}/${format}`;
  }
