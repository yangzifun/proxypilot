  // 生成原始订阅（Base64编码）
  static async generateRawSubscription(uuid) {
    const configs = await db('configs')
      .where({ uuid })
      .select('meta')
      .orderBy('created_at', 'desc');
    
    if (configs.length === 0) {
      return {
        success: false,
        error: 'No configurations found'
      };
    }
    
    // 将配置转换为VMess格式
    const vmessConfigs = configs.map(config => {
      const meta = JSON.parse(config.meta);
      
      if (meta.protocol === 'vmess') {
        return {
          v: '2',
          ps: meta.ps || '',
          add: meta.add || '',
          port: meta.port || '',
          id: meta.id || '',
          aid: meta.aid || '',
          net: meta.net || '',
          type: meta.type || '',
          host: meta.host || '',
          path: meta.path || '',
          tls: meta.tls || '',
          sni: meta.sni || ''
        };
      }
      // 其他协议转换为VMess格式（简化）
      return {
        v: '2',
        ps: meta.remark || meta.ps || 'Proxy Node',
        add: meta.add || meta.address || '',
        port: meta.port || '',
        id: '00000000-0000-0000-0000-000000000000',
        aid: '0',
        net: 'tcp',
        type: 'none'
      };
    });
    
    // 编码为Base64
    const jsonString = JSON.stringify(vmessConfigs);
    const base64String = Buffer.from(jsonString).toString('base64');
    
    return {
      success: true,
      subscription: base64String,
      configCount: configs.length
    };
  }

  // 生成Clash配置
  static async generateClashConfig(uuid, templateUrl = null) {
    const configs = await db('configs')
      .where({ uuid })
      .select('meta')
      .orderBy('created_at', 'desc');
    
    if (configs.length === 0) {
      return {
        success: false,
        error: 'No configurations found'
      };
    }
    
    // 获取模板
    let template = null;
    if (templateUrl) {
      try {
        // 这里可以扩展为从数据库或URL获取模板
        template = await this.fetchTemplate(templateUrl);
      } catch (error) {
        console.warn('Failed to fetch template:', error.message);
      }
    }
    
    // 如果没有模板，使用默认Clash配置
    if (!template) {
      template = this.getDefaultClashTemplate();
    }
    
    // 生成代理配置
    const proxies = configs.map((config, index) => {
      const meta = JSON.parse(config.meta);
      return this.generateClashProxy(meta, index + 1);
    }).filter(proxy => proxy !== null);
    
    // 替换模板中的代理列表
    const finalConfig = this.replaceTemplatePlaceholders(template, {
      proxies: JSON.stringify(proxies, null, 2),
      proxy_names: proxies.map(p => p.name).join(', '),
      timestamp: new Date().toISOString(),
      uuid: uuid
    });
    
    return {
      success: true,
      config: finalConfig,
      configCount: configs.length,
      proxyCount: proxies.length
    };
  }

